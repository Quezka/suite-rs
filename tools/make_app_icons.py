"""Writes every suite app's icon from one template: a rounded square in the app's own plain colour (no gradient)
with a white Material Symbol (filled, Apache 2.0) in the middle. Outputs, under icons/apps/:
  <app>.svg              desktop icon (128 box) and Quay's bundle
  <app>_foreground.xml   Android adaptive-icon foreground (108 dp, glyph inside the 66 dp safe zone)
  <app>_background.xml   Android adaptive-icon background colour
Run: python3 tools/make_app_icons.py  (needs the network once; glyphs come from Google's repository)."""
import re
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

BASE = "https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web"

# app: (material symbol, colour). Colours are tone-40 so white on them passes WCAG AA.
APPS = {
    "quire": ("auto_stories", "#4F46E5"),
    "ligature": ("schema", "#7C3AED"),
    "gantry": ("view_timeline", "#1D4ED8"),
    "folio": ("database", "#0F766E"),
    "facet": ("deployed_code", "#C2410C"),
    "bivouac": ("camping", "#15803D"),
    "missive": ("mail", "#B45309"),
    "natter": ("chat", "#047857"),
    "stagno": ("travel_explore", "#0369A1"),
    "quay": ("install_desktop", "#334155"),
    "loupe": ("videocam", "#BE123C"),
    "tether": ("devices", "#0E7490"),
    "cadence": ("fitness_center", "#B91C1C"),
    "vesper": ("bedtime", "#312E81"),
    "pillion": ("two_wheeler", "#A16207"),
    "tidings": ("newspaper", "#9333EA"),
}

OUT = Path(__file__).resolve().parent.parent / "icons" / "apps"


def glyph(symbol: str) -> str:
    url = f"{BASE}/{symbol}/materialsymbolsrounded/{symbol}_wght500fill1_24px.svg"
    svg = urllib.request.urlopen(url, timeout=30).read().decode()
    paths = re.findall(r' d="([^"]+)"', svg)
    if not paths:
        raise SystemExit(f"no path in {symbol}")
    return " ".join(paths)


def desktop(path: str, colour: str) -> str:
    # 112 square at 8, corner 28 (kit OUTER_RADIUS); glyph 64 centred. Symbol box: 0 -960 960 960.
    s = 64 / 960
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 128 128">'
            f'<rect x="8" y="8" width="112" height="112" rx="28" fill="{colour}"/>'
            f'<path fill="#FFFFFF" transform="translate(32 96) scale({s:.6f})" d="{path}"/></svg>\n')


def foreground(path: str) -> str:
    # 108 dp canvas; glyph 54 dp centred (inside the 66 dp circle every launcher mask keeps).
    s = 54 / 960
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- generated by suite-rs/tools/make_app_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="27" android:translateY="81" android:scaleX="{s:.6f}" android:scaleY="{s:.6f}">
        <path android:fillColor="#FFFFFF" android:pathData="{path}"/>
    </group>
</vector>
"""


def background(colour: str) -> str:
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- generated by suite-rs/tools/make_app_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="{colour}" android:pathData="M0,0h108v108h-108z"/>
</vector>
"""


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    with ThreadPoolExecutor(8) as pool:
        glyphs = dict(zip(APPS, pool.map(lambda a: glyph(APPS[a][0]), APPS)))
    for app, (_symbol, colour) in APPS.items():
        (OUT / f"{app}.svg").write_text(desktop(glyphs[app], colour), encoding="utf-8")
        (OUT / f"{app}_foreground.xml").write_text(foreground(glyphs[app]), encoding="utf-8")
        (OUT / f"{app}_background.xml").write_text(background(colour), encoding="utf-8")
    print(len(APPS), "app icons in", OUT)


if __name__ == "__main__":
    main()
