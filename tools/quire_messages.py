"""Writes crates/quire/src/presentation/messages.rs from the Python Quire's catalogues
(quire/presentation/locales/it.py, ru.py), so both apps say the same words.
Run from suite-rs/ after the Python catalogues change: python3 tools/quire_messages.py"""
import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCALES = ROOT.parent / "quire/quire/presentation/locales"


def load(code):
    spec = importlib.util.spec_from_file_location(code, LOCALES / f"{code}.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def rs(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def names(module, const):
    n = module.NAMES
    def arr(key, fallback=None):
        return "[" + ", ".join(rs(x) for x in n.get(key) or n[fallback]) + "]"
    return (f"pub const {const}: Names = Names {{\n    weekdays: {arr('weekdays')},\n    weekdays_short: {arr('weekdays_short')},\n"
            f"    months: {arr('months')},\n    months_genitive: {arr('months_genitive', 'months')},\n"
            f"    months_short: {arr('months_short')},\n}};\n")


def main():
    it, ru = load("it"), load("ru")
    keys = sorted(set(it.MESSAGES) | set(ru.MESSAGES))
    rows = [f"    ({rs(k)}, {rs(it.MESSAGES.get(k, k))}, {rs(ru.MESSAGES.get(k, k))})," for k in keys]
    words = sorted(set(it.PLURALS) & set(ru.PLURALS))
    plurals = [f"    ({rs(w)}, {rs(it.PLURALS[w][0])}, {rs(it.PLURALS[w][1])}, {', '.join(rs(x) for x in ru.PLURALS[w])}),"
               for w in words]
    out = ["//! Generated by tools/quire_messages.py from the Python Quire's catalogues: edit those, not this.",
           "",
           "use quezka_kit::i18n::{Messages, Names, Plurals};",
           "",
           "pub const MESSAGES: Messages = &[", *rows, "];",
           "",
           "pub const PLURALS: Plurals = &[", *plurals, "];",
           "",
           names(it, "IT_NAMES"), names(ru, "RU_NAMES")]
    path = ROOT / "crates/quire/src/presentation/messages.rs"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out))
    print(len(rows), "messages,", len(plurals), "plurals")


main()
