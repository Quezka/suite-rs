"""Writes the suite's tokens (design/tokens.json) into every codebase. `--check` only reports files that differ.

    python3 tools/gen_tokens.py [--check]      (from suite-rs; the other repos sit next to it)
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
REPOS = HERE.parent
T = json.loads((HERE / "design/tokens.json").read_text())
THEMES = {"light": "LIGHT", "dark": "DARK", "high-light": "HIGH_LIGHT", "high-dark": "HIGH_DARK"}
COLORS = {t["name"]: t["value"] for t in T["color"]["tokens"]}
px = lambda v: float(str(v).rstrip("px"))
RADIUS = {t["name"]: px(t["value"]) for t in T["radius"]["tokens"]}
SPACE = {t["name"]: px(t["value"]) for t in T["spacing"]["tokens"]}
TYPE = {s["name"]: (px(s["fontSize"]), px(s["lineHeight"]), int(s["fontWeight"])) for s in T["type"]["groups"][0]["styles"]}
GLASS = {t["name"]: float(t["value"]) for t in T["opacity"]["tokens"]}
HEADER = "Generated by suite-rs/tools/gen_tokens.py from design/tokens.json: edit the tokens there, not here."
const = lambda n: re.sub(r"[^A-Z0-9]", "_", n.upper())
snake = lambda n: n.replace("-", "_")
outputs = {}

# ---- Rust kit --------------------------------------------------------------------------------------------------
rs = [f"//! {HEADER}", "", "use crate::theme::Tokens;", "", "const fn hex(rgb: u32) -> egui::Color32 {",
      "    egui::Color32::from_rgb((rgb >> 16) as u8, (rgb >> 8) as u8, rgb as u8)", "}", ""]
for theme, name in THEMES.items():
    rs.append(f"pub const {name}: Tokens = Tokens {{")
    for c, v in COLORS.items():
        rs.append(f"    {snake(c)}: hex(0x{v[theme][1:]}),")
    rs += [f"    dark: {'true' if 'dark' in theme else 'false'},", f"    high_contrast: {'true' if 'high' in theme else 'false'},", "};", ""]
rs += [f"pub const {const(k)}: f32 = {v};" for k, v in RADIUS.items()]
rs += [f"pub const {const(k)}: f32 = {v};" for k, v in SPACE.items()]
rs.append("/// Type styles: (size, line height, weight).")
rs += [f"pub const TYPE_{const(k)}: (f32, f32, u16) = ({a}, {b}, {c});" for k, (a, b, c) in TYPE.items()]
rs += [f"pub const {const(k)}: f32 = {v};" for k, v in GLASS.items()]
outputs[HERE / "crates/kit/src/tokens.rs"] = "\n".join(rs) + "\n"

# ---- Python kit --------------------------------------------------------------------------------------------------
py = [f'"""{HEADER}"""', "", "THEMES = {"]
for theme in THEMES:
    py.append(f"    {theme!r}: {{" + ", ".join(f"{snake(c)!r}: {v[theme]!r}" for c, v in COLORS.items()) + "},")
py += ["}", f"RADIUS = {RADIUS!r}", f"SPACE = {SPACE!r}",
       "# (size px, line height px, weight); Qt point sizes are px * 0.75.", f"TYPE = {TYPE!r}", f"GLASS = {GLASS!r}", "",
       "", "def pt(style: str) -> float:", "    return round(TYPE[style][0] * 0.75, 2)"]
outputs[REPOS / "suite-kit/quezka_ui/tokens.py"] = "\n".join(py) + "\n"

# ---- Kotlin phone apps -----------------------------------------------------------------------------------------
def kt(package):
    c = lambda name, theme: f"Color(0xFF{COLORS[name][theme][1:].upper()})"
    def scheme(theme, fn):
        g = lambda n: c(n, theme)
        return (f"    val {THEMES[theme].title().replace('_', '')}: ColorScheme = {fn}(\n"
                f"        primary = {g('accent')}, onPrimary = {g('on-accent')},\n"
                f"        primaryContainer = {g('accent-soft')}, onPrimaryContainer = {g('on-accent-soft')},\n"
                f"        secondaryContainer = {g('accent-soft')}, onSecondaryContainer = {g('on-accent-soft')},\n"
                f"        background = {g('bg')}, onBackground = {g('text')},\n"
                f"        surface = {g('bg')}, onSurface = {g('text')},\n"
                f"        surfaceVariant = {g('raised')}, onSurfaceVariant = {g('muted')},\n"
                f"        surfaceContainer = {g('sidebar')}, surfaceContainerLow = {g('surface')},\n"
                f"        surfaceContainerHigh = {g('surface')}, surfaceContainerHighest = {g('raised')},\n"
                f"        outline = {g('border')}, outlineVariant = {g('hover')},\n"
                f"        error = {g('danger')}, tertiary = {g('success')},\n    )\n")
    roles = [("displayLarge", 40, 46, 800), ("displayMedium", 36, 42, 800), ("displaySmall", *TYPE["display"]),
             ("headlineLarge", 28, 34, 700), ("headlineMedium", *TYPE["headline"]), ("headlineSmall", 24, 30, 700),
             ("titleLarge", *TYPE["title-lg"]), ("titleMedium", *TYPE["title"]), ("titleSmall", 16, 22, 600),
             ("bodyLarge", *TYPE["body-lg"]), ("bodyMedium", *TYPE["body"]), ("bodySmall", *TYPE["caption"]),
             ("labelLarge", *TYPE["label"]), ("labelMedium", 14, 20, 600), ("labelSmall", *TYPE["caption"])]
    styles = ",\n".join(f"        {r} = TextStyle(fontFamily = family, fontSize = {int(s)}.sp, lineHeight = {int(l)}.sp, fontWeight = FontWeight({w}))" for r, s, l, w in roles)
    return (f"// {HEADER}\npackage {package}\n\nimport androidx.compose.material3.ColorScheme\nimport androidx.compose.material3.Typography\n"
            "import androidx.compose.material3.darkColorScheme\nimport androidx.compose.material3.lightColorScheme\n"
            "import androidx.compose.ui.graphics.Color\nimport androidx.compose.ui.text.TextStyle\nimport androidx.compose.ui.text.font.FontFamily\n"
            "import androidx.compose.ui.text.font.FontWeight\nimport androidx.compose.ui.unit.dp\nimport androidx.compose.ui.unit.sp\n\n"
            "object SuiteTokens {\n" + scheme("light", "lightColorScheme") + scheme("dark", "darkColorScheme") + scheme("high-light", "lightColorScheme") + scheme("high-dark", "darkColorScheme") +
            "".join(f"    val {snake(k).upper()} = {int(v)}.dp\n" for k, v in {**RADIUS, **SPACE}.items() if v < 900) +
            f"\n    fun typography(family: FontFamily) = Typography(\n{styles},\n    )\n}}\n")

for repo, pkg in (("quire/android/app/src/main/java/io/github/quezka/quire/ui", "io.github.quezka.quire.ui"),
                  ("cadence/app/src/main/java/io/github/quezka/cadence/ui", "io.github.quezka.cadence.ui"),
                  ("vesper/app/src/main/java/io/github/quezka/vesper/ui", "io.github.quezka.vesper.ui")):
    outputs[REPOS / repo / "SuiteTokens.kt"] = kt(pkg)

# ---- Pillion (its own Tokens struct; colour fields rewritten in place) ------------------------------------------
pil = REPOS / "neos-companion/app/src/ui/theme.rs"
if pil.exists():
    text = pil.read_text()
    for theme, name in THEMES.items():
        start = text.index(f"pub const {name}: Tokens = Tokens {{")
        end = text.index("};", start)
        block = text[start:end]
        for c, v in COLORS.items():
            block = re.sub(rf"(\n    {snake(c)}: hex\(0x)[0-9a-f]{{6}}\)", lambda m: m.group(1) + v[theme][1:] + ")", block)
        text = text[:start] + block + text[end:]
    outputs[pil] = text

stale = [p for p, s in outputs.items() if not p.exists() or p.read_text() != s]
if "--check" in sys.argv:
    print("\n".join(f"stale: {p}" for p in stale) or "all in step")
    sys.exit(1 if stale else 0)
for p in stale:
    p.write_text(outputs[p])
    print("wrote", p)
