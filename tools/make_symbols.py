"""Writes src/ui/symbols.rs: Google's Material Symbols (Outlined, Apache 2.0), fetched the way suite-kit's
tools/make_symbols.py fetches them, so the icons match the rest of the suite.
Run from app/ after changing MAP: python3 tools/make_symbols.py"""
import re
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

BASE = "https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web"
WEIGHT = 500
# The kit's own names where it has them, so a name keeps its meaning across the suite.
MAP = {
    "alert": "warning", "arrow-back": "arrow_back", "bell": "notifications", "check": "check",
    "chevron-right": "chevron_right", "flag": "flag", "play": "play_arrow", "refresh": "refresh", "reset": "restart_alt",
    "search": "search", "settings": "settings", "target": "my_location", "x": "close",
    # Pillion's
    "battery": "battery_horiz_075", "bluetooth": "bluetooth", "bolt": "bolt", "call": "call", "hearing": "hearing",
    "history": "history", "moped": "electric_moped", "route": "directions", "turn-left": "turn_left",
    "turn-right": "turn_right", "turn-sharp-left": "turn_sharp_left", "turn-sharp-right": "turn_sharp_right",
    "turn-slight-left": "turn_slight_left", "turn-slight-right": "turn_slight_right", "turn-straight": "straight",
    "u-turn-left": "u_turn_left", "u-turn-right": "u_turn_right", "voice": "record_voice_over",
    "volume": "volume_up",
    # The map and saved places (0.3.0)
    "star": "star", "home": "home", "work": "work", "plus": "add", "minus": "remove", "pin": "location_on",
    "speed": "speed", "map": "map", "delete": "delete", "near": "near_me",
}


def fetch(symbol: str, filled: bool) -> str | None:
    fill = "fill1" if filled else ""
    url = f"{BASE}/{symbol}/materialsymbolsoutlined/{symbol}_wght{WEIGHT}{fill}_24px.svg"
    try:
        svg = urllib.request.urlopen(url, timeout=30).read().decode()
    except urllib.error.HTTPError:
        return None
    return "".join(re.findall(r' d="([^"]+)"', svg)) or None


def one(item):
    name, symbol = item
    outline = fetch(symbol, False)
    if outline is None:
        raise SystemExit(f"no such symbol: {symbol}")
    filled = fetch(symbol, True)
    return name, outline, filled or outline


def main():
    with ThreadPoolExecutor(8) as pool:
        rows = sorted(pool.map(one, MAP.items()))
    lines = [
        "//! Generated by tools/make_symbols.py: Material Symbols Outlined by Google, Apache License 2.0",
        "//! (assets/MaterialSymbols-LICENSE.txt). Path data in a 0 -960 960 960 box.",
        "",
        "/// (name, outlined path, filled path)",
        "pub const SYMBOLS: &[(&str, &str, &str)] = &[",
    ]
    lines += [f'    ("{n}", "{o}", "{f}"),' for n, o, f in rows]
    lines.append("];")
    Path("src/ui/symbols.rs").write_text("\n".join(lines) + "\n")
    print(len(rows), "symbols")


main()
